#!/usr/bin/env python3
"""
Headless Blender 5.2 Cycles per-light indirect lightmap + 3D L1 SH probe baker for @arcade/kit.

Consumes the canonical engine-exported `BakeSceneSpec` JSON (`scripts/house-bake-scene.json`, generated by
`exportHouseBakeSceneSpec()` in `packages/kit/lab/world/scene.ts`), unwraps UV2 with Blender's
`bpy.ops.uv.lightmap_pack`, bakes each light with its exact live emitter shape/cone/power and zero fudge factors,
verifies 1-bounce Cycles irradiance against the closed-form analytic spot-floor integral, and writes
`packages/kit/gpu/gi/house-lightmap-data.ts` with `blenderVersion` and `inputHash` (SHA-256).

Usage (via HiveMind on Mac mini):
  hivemind run --priority high --kind cargo --worker mini -- \\
    /Applications/Blender.app/Contents/MacOS/Blender -b --factory-startup -P scripts/bake-room.py -- \\
    --scene scripts/house-bake-scene.json \\
    --out packages/kit/gpu/gi/house-lightmap-data.ts \\
    --size 128 --samples 96
"""

