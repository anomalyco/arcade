// Coverage-preserving alpha for the forest's cut-out layers (Castaño, "Computing Alpha Mipmaps"): for each layer and mip
// level of a 1024² base, the scale that keeps the share of texels above the cut-off what it is at full resolution, so
// cards neither thin out nor fill into rectangles with distance. Writes packages/kit/forest/alpha-coverage.ts.
//   bun scripts/woods/alpha-coverage.ts
import { $ } from "bun"
import { writeFileSync } from "node:fs"
import { join } from "node:path"

const root = join(import.meta.dir, "../../packages/kit/forest/assets")
const CUTOFF = 0.5
const SIZE = 1024
const LEVELS = 11
const layers = { "twig-fir": "tex/twig-fir-base.webp", "twig-pine": "tex/twig-pine-base.webp", fern: "models/fern-base.webp" } as const

const coverage = (a: Float32Array, s: number) => { let n = 0; for (let i = 0; i < a.length; i++) if (a[i]! * s > CUTOFF) n++; return n / a.length }

const table: Record<string, number[]> = {}
for (const [name, file] of Object.entries(layers)) {
  const raw = await $`magick ${join(root, file)} -resize ${SIZE}x${SIZE}! -alpha extract -depth 8 gray:-`.arrayBuffer()
  let a = Float32Array.from(new Uint8Array(raw), (v) => v / 255)
  let size = SIZE
  const target = coverage(a, 1)
  const scales: number[] = []
  for (let level = 0; level < LEVELS; level++) {
    // Bisect the scale whose coverage matches full resolution.
    let lo = 0.25, hi = 8
    for (let k = 0; k < 30; k++) { const m = (lo + hi) / 2; if (coverage(a, m) < target) lo = m; else hi = m }
    scales.push(+((lo + hi) / 2).toFixed(3))
    if (size === 1) break
    const half = size / 2, next = new Float32Array(half * half)
    for (let y = 0; y < half; y++) for (let x = 0; x < half; x++) next[y * half + x] = (a[2 * y * size + 2 * x]! + a[2 * y * size + 2 * x + 1]! + a[(2 * y + 1) * size + 2 * x]! + a[(2 * y + 1) * size + 2 * x + 1]!) / 4
    a = next; size = half
  }
  table[name] = scales
  console.log(name, "coverage", target.toFixed(3), scales.join(" "))
}

writeFileSync(join(import.meta.dir, "../../packages/kit/forest/alpha-coverage.ts"), `// Generated by scripts/woods/alpha-coverage.ts: per cut-out layer, the alpha scale at each mip of a ${SIZE}² base that
// keeps its coverage above ${CUTOFF} what it is at full resolution.
export const ALPHA_COVERAGE_BASE = ${SIZE}
export const ALPHA_COVERAGE: Record<"twig-fir" | "twig-pine" | "fern", readonly number[]> = ${JSON.stringify(table)}
`)
