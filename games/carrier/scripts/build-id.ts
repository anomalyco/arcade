// Writes shared/build.gen.ts: a hash of everything in shared/ (protocol, sea, islands). The client sends it in its
// hello; a server built from different shared code tells the client to reload, so old tabs never talk an old protocol.
import { createHash } from "node:crypto"
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs"
import { join, relative } from "node:path"

const root = join(import.meta.dir, "..")
const shared = join(root, "shared")
const out = join(shared, "build.gen.ts")
if (!existsSync(shared)) mkdirSync(shared)
const files: string[] = []
const walk = (dir: string) => {
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name)
    if (p === out) continue
    if (statSync(p).isDirectory()) walk(p)
    else if (p.endsWith(".ts")) files.push(p)
  }
}
walk(shared)
const h = createHash("sha256")
for (const f of files) h.update(relative(root, f)).update("\0").update(readFileSync(f)).update("\0")
const id = h.digest("hex").slice(0, 12)
writeFileSync(out, `// Generated by scripts/build-id.ts. Do not edit.\nexport const BUILD = "${id}"\n`)
console.log(`build ${id}`)
