const SHOUT = "[shouting as loud as possible into a dark forest at night, hands cupped round the mouth, full chest voice, long held vowels]"
const SHOUT_TIRED = "[shouting hoarsely into the dark woods, out of breath from walking uphill through brush, voice straining]"
const CALL = "[calling out loudly across the dark woods to someone forty metres away]"
const TALK = "[talking to someone a few steps away, at night]"
const QUIET = "[quiet, close, shaken, almost a whisper, in a dark forest at night]"

type Row = [Pool, Loudness, string, string?]
const lines = (cast: CastId, rows: Row[]): VoiceLineSpec[] => {
  const n: Record<string, number> = {}
  return rows.map(([pool, loud, text, direct]) => {
    n[pool] = (n[pool] ?? 0) + 1
    const tag = direct ?? (loud === "shout" ? SHOUT : loud === "call" ? CALL : loud === "quiet" ? QUIET : TALK)
    return { id: `${cast}.${pool}.${n[pool]}`, cast, pool, loud, text, direct: `${tag} ${text}` }
  })
}

