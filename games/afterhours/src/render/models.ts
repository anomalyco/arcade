// Realistic prop and vehicle library: one web-optimised .glb per model in public/models/, fetched and normalised by
// scripts/fetch-models.ts (sources and licences in public/models/CREDITS.md; CC BY and CC BY-SA ones need the credit lines).
//
// Conventions for every model:
//   - metres, Y up, real-world scale;
//   - pivot (local origin) at the centre of the footprint, on the ground (lowest vertex at y = 0);
//   - the model's front faces -Z (car noses, desk/terminal/chair fronts, the open face of wall-mounted units).
//     So `object.rotation.y = yaw` turns the front to (-sin yaw, 0, -cos yaw); `yawToward(dx, dz)` gives the yaw that
//     points the front along a direction;
//   - transforms are baked, so every mesh sits directly under the returned group with an identity transform and
//     clones/instances can share geometry and materials.
//
// Placing many props — which to use:
//   - static props (furniture, crates, dock clutter, parked cars): `mergeModels(placements)` + `modelColliders(...)`.
//     Bakes everything into one plain mesh per shared material: ~2 draws per call, zero extra shader builds. Call it
//     per room/area so culling still works.
//   - props that move or change per instance, or very large sets (hundreds+ of one model): `instanceModel(...)`.
//     Its InstancedMeshes reserve capacity ≥ 1025 so they all share one vertex program (r186 bakes smaller counts
//     into a per-mesh shader); still one call per model with all placements.
//   - a single hero object you animate or tweak: `loadModel(name)`.
//
// `size` is the axis-aligned bounding box [x, y, z] in metres at scale 1 (x = width, z = length/depth); use it, or
// `modelCollider`, for colliders.
//
// LOD: models whose MODELS entry has `lod1` (its triangle count) also carry a simplified copy in the same .glb, same
// materials and atlas (no extra textures or shaders). Ask for it with `loadModel(name, { lod: 1 })` or
// `instanceModel(name, placements, { lod: 1 })`; for models without one, `lod: 1` returns the full model. Distance
// switching is up to the caller (e.g. a THREE.LOD with `addLevel(await loadModel(n), 0)` and
// `addLevel(await loadModel(n, { lod: 1 }), 12)`, or LOD1 instances for far rows of cars).

