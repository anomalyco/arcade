/**
 * A material in the exact layout every model material has (same node program and pipeline), over a KTX2 atlas set
 * outside the glTF files — used by src/render/documents.ts. Returns at once; the textures stream in.
 *   base: sRGB colour; normal: tangent-space OpenGL; orm: R occlusion, G roughness, B metalness.
 */
export function atlasMaterial(urls: { base: string; normal: string; orm: string }, name = "atlas"): THREE.Material {
  const tex = (srgb: boolean) => {
    // Same sampler state as glTF textures (repeat, trilinear) so the cache key matches the models'.
    const t = new THREE.CompressedTexture([], 1, 1)
    t.wrapS = t.wrapT = THREE.RepeatWrapping
    t.minFilter = THREE.LinearMipmapLinearFilter
    t.magFilter = THREE.LinearFilter
    t.colorSpace = srgb ? THREE.SRGBColorSpace : THREE.NoColorSpace
    t.flipY = false
    return t
  }
  const map = tex(true)
  const normalMap = tex(false)
  const orm = tex(false)
  const m = new THREE.MeshStandardMaterial({ map, normalMap, roughnessMap: orm, metalnessMap: orm, aoMap: orm, roughness: 1, metalness: 1, side: THREE.DoubleSide })
  m.name = name
  const n = toNodeMaterial(m)
  canonicalise(n)
  void ensureKtx2().then(() =>
    Promise.all(
      ([[map, urls.base], [normalMap, urls.normal], [orm, urls.orm]] as const).map(([t, url]) =>
        ktx2.loadAsync(url).then((src) => {
          t.mipmaps = src.mipmaps
          t.image = src.image
          t.format = src.format
          t.type = src.type
          t.generateMipmaps = false
          t.needsUpdate = true
          src.dispose()
        }),
      ),
    ),
  )
  return n
}

/** Drops vertex attributes the material can't read (they still split the shader key) and widens quantised UVs so
 *  every model geometry has the same attribute layout. */
function canonicaliseGeometry(g: THREE.BufferGeometry, mats: THREE.Material[]) {
  if (!mats.some((m) => m.vertexColors)) g.deleteAttribute("color")
  const channels = new Set<number>()
  for (const m of mats)
    for (const v of Object.values(m)) if ((v as THREE.Texture | null)?.isTexture) channels.add((v as THREE.Texture).channel)
  for (let ch = 1; ch < 4; ch++) if (!channels.has(ch)) g.deleteAttribute(`uv${ch}`)
  if (!g.getAttribute("uv")) g.setAttribute("uv", new THREE.BufferAttribute(new Float32Array(g.getAttribute("position").count * 2), 2))
  for (const name of Object.keys(g.attributes)) {
    if (!name.startsWith("uv")) continue
    const a = g.getAttribute(name) as THREE.BufferAttribute | THREE.InterleavedBufferAttribute
    if (!a.normalized && a.array instanceof Float32Array && !(a as THREE.InterleavedBufferAttribute).isInterleavedBufferAttribute) continue
    const f = new Float32Array(a.count * a.itemSize)
    for (let i = 0; i < a.count; i++) for (let k = 0; k < a.itemSize; k++) f[i * a.itemSize + k] = a.getComponent(i, k)
    g.setAttribute(name, new THREE.BufferAttribute(f, a.itemSize))
  }
}

function prepare(name: ModelName, root: THREE.Group): THREE.Group {
  const info: ModelInfo = MODELS[name]
  const small = Math.max(...info.size) < 0.35
  const converted = new Map<THREE.Material, THREE.Material>()
  const convert = (m: THREE.Material) => {
    let n = converted.get(m)
    if (n) return n
    n = toNodeMaterial(m)
    if (modelMaterialSharing.enabled) {
      canonicalise(n)
      const key = materialSignature(n)
      const hit = shared.get(key)
      if (hit) {
        n.dispose()
        n = hit
      } else shared.set(key, n)
    }
    converted.set(m, n)
    return n
  }
  root.name = name
  root.traverse((o) => {
    const mesh = o as THREE.Mesh
    if (!mesh.isMesh) return
    mesh.material = Array.isArray(mesh.material) ? mesh.material.map(convert) : convert(mesh.material)
    if (modelMaterialSharing.enabled) canonicaliseGeometry(mesh.geometry, Array.isArray(mesh.material) ? mesh.material : [mesh.material])
    const mats = Array.isArray(mesh.material) ? mesh.material : [mesh.material]
    const seeThrough = mats.every((m) => m.transparent || ((m as THREE.MeshPhysicalMaterial).transmission ?? 0) > 0)
    // Tiny desk props don't need shadow-map draws; glass never casts.
    mesh.castShadow = !small && !seeThrough
    mesh.receiveShadow = true
  })
  root.userData.model = name
  return root
}

export type ModelOptions = {
  /** 0 = full model (default), 1 = simplified LOD1 (falls back to 0 when the model has none; see MODELS[name].lod1). */
  lod?: 0 | 1
}

/** Loads (once) and returns a fresh clone of a model. Clones share geometry and materials, and materials may be
 *  shared across different models too: clone a material before changing it. */
export async function loadModel(name: ModelName, options: ModelOptions = {}): Promise<THREE.Group> {
  let t = templates.get(name)
  if (!t) {
    t = ensureKtx2()
      .then(() => loader.loadAsync(`${BASE}${name}.glb`))
      .then((gltf) => prepare(name, gltf.scene as unknown as THREE.Group))
    templates.set(name, t)
    t.catch(() => templates.delete(name))
  }
  const template = await t
  const level = template.getObjectByName(`lod${options.lod ?? 0}`) ?? template.getObjectByName("lod0")
  if (!level) return template.clone()
  const g = new THREE.Group()
  g.name = template.name
  g.userData.model = name
  g.userData.lod = level.name === "lod1" ? 1 : 0
  for (const c of level.children) g.add(c.clone())
  return g
}

/** Starts loading models in the background (e.g. the ones near the first view). */
export function preloadModels(names: readonly ModelName[]) {
  for (const n of names) void loadModel(n).catch(() => {})
}

export type Placement = {
  position: readonly [number, number, number]
  /** Radians about +Y (see MODEL_FORWARD). */
  yaw?: number
  /** Uniform scale, or per-axis. */
  scale?: number | readonly [number, number, number]
}

const tmpM = new THREE.Matrix4()
const tmpQ = new THREE.Quaternion()
const tmpP = new THREE.Vector3()
const tmpS = new THREE.Vector3()
const UP = new THREE.Vector3(0, 1, 0)

const placementMatrix = (p: Placement, out: THREE.Matrix4) => {
  const s = p.scale ?? 1
  if (typeof s === "number") tmpS.setScalar(s)
  else tmpS.set(s[0], s[1], s[2])
  return out.compose(tmpP.set(p.position[0], p.position[1], p.position[2]), tmpQ.setFromAxisAngle(UP, p.yaw ?? 0), tmpS)
}

/** One InstancedMesh per sub-mesh of a model, for repeated props (barrels, pallets, chairs, cones). Accepts placements
 *  or ready-made matrices. The meshes share the model's geometry and materials. Each InstancedMesh compiles its own
 *  shader in r186, so make one call per model with every placement. */
export async function instanceModel(
  name: ModelName,
  transforms: readonly (Placement | THREE.Matrix4)[],
  options: ModelOptions = {},
): Promise<THREE.Group> {
  const template = await loadModel(name, options)
  const group = new THREE.Group()
  group.name = `${name}×${transforms.length}`
  const matrices = transforms.map((t) => (t instanceof THREE.Matrix4 ? t : placementMatrix(t, new THREE.Matrix4())))
  template.updateMatrixWorld(true)
  template.traverse((o) => {
    const mesh = o as THREE.Mesh
    if (!mesh.isMesh) return
    // Capacity ≥ 1025: below that three r186 bakes the instance count into a uniform-array vertex shader, one program
    // per InstancedMesh; above it the matrices are a vertex attribute and every InstancedMesh shares the program.
    const inst = new THREE.InstancedMesh(mesh.geometry, mesh.material, Math.max(INSTANCE_CAPACITY, matrices.length))
    inst.count = matrices.length
    inst.name = mesh.name
    inst.castShadow = mesh.castShadow
    inst.receiveShadow = mesh.receiveShadow
    const local = mesh.matrixWorld
    for (let i = 0; i < matrices.length; i++) inst.setMatrixAt(i, tmpM.multiplyMatrices(matrices[i]!, local))
    inst.instanceMatrix.needsUpdate = true
    inst.computeBoundingBox()
    inst.computeBoundingSphere()
    group.add(inst)
  })
  return group
}

const INSTANCE_CAPACITY = 1025

export type MergePlacement = Placement & {
  name: ModelName
  lod?: 0 | 1
  /** Shadow casting for this placement (default: the model's own setting, i.e. off for tiny props and glass). */
  cast?: boolean
}

/** Copy of an attribute as plain float data (glTF quantised/normalised/interleaved attributes don't survive a matrix
 *  bake or a merge with other models). */
function floatAttribute(a: THREE.BufferAttribute | THREE.InterleavedBufferAttribute) {
  const out = new Float32Array(a.count * a.itemSize)
  for (let i = 0; i < a.count; i++) for (let k = 0; k < a.itemSize; k++) out[i * a.itemSize + k] = a.getComponent(i, k)
  return new THREE.BufferAttribute(out, a.itemSize)
}

/**
 * Bakes static placements of any models into one plain Mesh per (material, shadow-casting) pair — all opaque models
 * share one material shader and all glass another, so a whole room of props is ~2–4 draws and adds no node builds.
 * Returns the group at once and fills it when the models have loaded (`group.userData.ready` is the promise).
 * Colliders: `modelColliders(placements)`. One merged mesh is culled as a whole, so call this per area/room rather
 * than once for the whole world.
 */
export function mergeModels(placements: readonly MergePlacement[]): THREE.Group {
  const group = new THREE.Group()
  group.name = `merged×${placements.length}`
  const ready = (async () => {
    const keys = [...new Set(placements.map((p) => `${p.name}:${p.lod ?? 0}`))]
    const templates = new Map<string, THREE.Group>()
    await Promise.all(
      keys.map(async (k) => {
        const [name, lod] = k.split(":") as [ModelName, string]
        const t = await loadModel(name, { lod: Number(lod) as 0 | 1 })
        t.updateMatrixWorld(true)
        templates.set(k, t)
      }),
    )
    const buckets = new Map<string, { material: THREE.Material; cast: boolean; geos: THREE.BufferGeometry[] }>()
    const m = new THREE.Matrix4()
    for (const p of placements) {
      const t = templates.get(`${p.name}:${p.lod ?? 0}`)!
      placementMatrix(p, tmpM)
      t.traverse((o) => {
        const mesh = o as THREE.Mesh
        if (!mesh.isMesh || Array.isArray(mesh.material)) return
        const src = mesh.geometry
        const g = new THREE.BufferGeometry()
        for (const n of ["position", "normal", "uv"]) {
          const a = src.getAttribute(n) as THREE.BufferAttribute | undefined
          if (a) g.setAttribute(n, floatAttribute(a))
        }
        if (src.index) g.setIndex(Array.from(src.index.array as ArrayLike<number>))
        else g.setIndex([...Array(g.getAttribute("position").count).keys()])
        g.applyMatrix4(m.multiplyMatrices(tmpM, mesh.matrixWorld))
        const cast = (p.cast ?? true) && mesh.castShadow
        const key = `${mesh.material.uuid}:${cast}`
        let b = buckets.get(key)
        if (!b) buckets.set(key, (b = { material: mesh.material, cast, geos: [] }))
        b.geos.push(g)
      })
    }
    for (const b of buckets.values()) {
      const merged = mergeGeometries(b.geos, false)
      for (const g of b.geos) g.dispose()
      if (!merged) continue
      merged.computeBoundingBox()
      merged.computeBoundingSphere()
      const mesh = new THREE.Mesh(merged, b.material)
      mesh.name = `${group.name}:${b.material.name || "material"}`
      mesh.castShadow = b.cast
      mesh.receiveShadow = true
      mesh.matrixAutoUpdate = false
      group.add(mesh)
    }
  })()
  group.userData.ready = ready
  ready.catch(() => {})
  return group
}

/** Colliders for a set of placements (mergeModels or otherwise); `inset` as in modelCollider. */
export function modelColliders(placements: readonly (Placement & { name: ModelName })[], inset = 0): Box[] {
  return placements.map((p) => modelCollider(p.name, p, inset))
}

/** World-space AABB of a placed model's bounding box (rotated footprint), optionally shrunk inward by `inset` metres
 *  on each horizontal side (cars and round props feel better slightly inset). Push the result into `ctx.colliders`. */
export function modelCollider(name: ModelName, p: Placement, inset = 0): Box {
  const [w, h, d] = MODELS[name].size as readonly [number, number, number]
  const s = p.scale ?? 1
  const [sx, sy, sz] = typeof s === "number" ? [s, s, s] : s
  const hx = Math.max(0.01, (w * sx) / 2 - inset)
  const hz = Math.max(0.01, (d * sz) / 2 - inset)
  const yaw = p.yaw ?? 0
  const c = Math.abs(Math.cos(yaw)), sn = Math.abs(Math.sin(yaw))
  const ex = hx * c + hz * sn
  const ez = hx * sn + hz * c
  const [x, y, z] = p.position
  return { min: [x - ex, y, z - ez], max: [x + ex, y + h * sy, z + ez] }
}
