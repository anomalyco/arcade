/** GLTFLoader builds classic materials; swap in the equivalent node material (what WebGPURenderer would do anyway) so
 *  owners can attach TSL nodes such as wetness or dirt. Same copy rule as three's NodeLibrary.fromMaterial. */
function toNodeMaterial(m: THREE.Material): THREE.Material {
  if ((m as { isNodeMaterial?: boolean }).isNodeMaterial) return m
  const Node = (m as THREE.MeshPhysicalMaterial).isMeshPhysicalMaterial
    ? THREE.MeshPhysicalNodeMaterial
    : (m as THREE.MeshStandardMaterial).isMeshStandardMaterial
      ? THREE.MeshStandardNodeMaterial
      : (m as THREE.MeshBasicMaterial).isMeshBasicMaterial
        ? THREE.MeshBasicNodeMaterial
        : null
  if (!Node) return m
  // Physical without any physical layer that shows (pallet, from spec-gloss; glass clear-coat under alpha blending)
  // renders like standard; downgrading saves a shader variant. Clear-coated car paint and sheen fabric stay physical.
  let Cls: typeof THREE.MeshStandardNodeMaterial | typeof THREE.MeshPhysicalNodeMaterial | typeof THREE.MeshBasicNodeMaterial = Node
  const ph = m as THREE.MeshPhysicalMaterial
  if (modelMaterialSharing.enabled && ph.isMeshPhysicalMaterial) {
    const layered = (!m.transparent && ph.clearcoat > 0) || ph.transmission > 0 || ph.sheen > 0 || ph.iridescence > 0 || ph.anisotropy > 0 || ph.dispersion > 0
    if (!layered) Cls = THREE.MeshStandardNodeMaterial
  }
  if (modelMaterialSharing.enabled && m.transparent) m.side = THREE.DoubleSide
  const n = new Cls() as unknown as Record<string, unknown>
  const skip = Cls !== Node ? physicalOnlyKeys() : SKIP_KEYS
  for (const key in m) if (!SKIP_KEYS.has(key) && !skip.has(key)) n[key] = (m as unknown as Record<string, unknown>)[key]
  m.dispose()
  return n as unknown as THREE.Material
}

// Shader variety. WebGPURenderer builds one node program + pipeline per distinct *structure*, not per material: its
// cache key (RenderObject.getMaterialCacheKey) sees which texture slots are filled (plus their sampler state), whether
// each numeric parameter is zero or non-zero, side/transparency/alphaTest, the material class and the geometry's
// attribute layout — never the texture images or exact values.
//   - At fetch time every model is baked to at most two materials (opaque + glass) over one KTX2 atlas
//     (scripts/fetch-models.ts), so a model is ≤ 2 draws and 1–2 materials.
//   - At load, every material is canonicalised to the same layout: all of map / normalMap / roughness+metalness /
//     aoMap / emissiveMap filled (neutral 1×1 textures where a model has none, e.g. no emissive), parameters off exact
//     zero, one vertex layout (position, normal, uv). Identical materials are shared.
// Result (`bun scripts/models-sheet.ts --q "stats=1"`, all 41 models): every opaque model uses one shader and every
// glass part another, differing only in their textures — 3 node programs / 3 pipelines total (was 34 / 23 with the
// raw per-part materials, 4 / 4 after the first sharing pass). Exception three can't share: every InstancedMesh gets
// its own program (r186 adds the object uuid to the key), so call instanceModel once per model with all placements.
/** A/B switch for measurement only (scripts/models-sheet-page.ts `raw=1`); leave enabled. */
export const modelMaterialSharing = { enabled: true }

const neutral = (rgba: [number, number, number, number], srgb: boolean) => {
  const t = new THREE.DataTexture(new Uint8Array(rgba), 1, 1)
  t.colorSpace = srgb ? THREE.SRGBColorSpace : THREE.NoColorSpace
  t.wrapS = t.wrapT = THREE.RepeatWrapping
  t.magFilter = THREE.LinearFilter
  t.minFilter = THREE.LinearMipmapLinearFilter
  t.generateMipmaps = true
  t.flipY = false
  t.needsUpdate = true
  return t
}
let neutrals: { white: THREE.DataTexture; linear: THREE.DataTexture; flat: THREE.DataTexture; black: THREE.DataTexture } | null = null
const getNeutrals = () =>
  (neutrals ??= {
    white: neutral([255, 255, 255, 255], true),
    linear: neutral([255, 255, 255, 255], false),
    flat: neutral([128, 128, 255, 255], false),
    black: neutral([0, 0, 0, 255], true),
  })

type Pbr = THREE.MeshStandardMaterial & Partial<THREE.MeshPhysicalMaterial>

/** Fills every PBR slot so all opaque model materials share one shader layout (see above). */
function canonicalise(m: THREE.Material) {
  const p = m as Pbr
  if (!p.isMeshStandardMaterial) return
  const n = getNeutrals()
  p.map ??= n.white
  p.normalMap ??= n.flat
  if (!p.roughnessMap && !p.metalnessMap) p.roughnessMap = p.metalnessMap = n.linear
  else {
    p.roughnessMap ??= n.linear
    p.metalnessMap ??= n.linear
  }
  p.aoMap ??= n.linear
  // A black emissive map only matters when the colour is black too, so either way the result is unchanged.
  if (!p.emissiveMap) p.emissiveMap = p.emissive.getHex() === 0 ? n.black : n.white
  p.emissiveIntensity ||= 1
  p.metalness = Math.max(p.metalness, 0.001)
  p.roughness = Math.max(p.roughness, 0.02)
  p.aoMapIntensity ||= 1
  p.envMapIntensity ||= 1
}

const q = (v: number, step: number) => Math.round(v / step)
const texKey = (t: THREE.Texture | null | undefined) =>
  t ? `${(t.source as { uuid: string }).uuid}:${t.channel}:${t.wrapS}${t.wrapT}${t.minFilter}${t.magFilter}:${t.offset.toArray()}${t.repeat.toArray()}${t.rotation}` : "-"

/** Identity of a material's look, with colours and scalars quantised so near-identical materials collapse. */
function materialSignature(m: THREE.Material): string {
  const p = m as Pbr & { color?: THREE.Color; isMeshBasicMaterial?: boolean }
  const c = (col: THREE.Color | undefined) => (col ? col.toArray().map((v) => q(v, 1 / 128)).join(".") : "-")
  const parts: unknown[] = [m.type, m.side, m.transparent, q(m.opacity, 0.02), q(m.alphaTest, 0.01), m.depthWrite, m.blending, m.vertexColors, c(p.color)]
  if (p.isMeshStandardMaterial) {
    parts.push(
      q(p.roughness, 0.02), q(p.metalness, 0.02), c(p.emissive), q(p.emissiveIntensity, 0.05), q(p.aoMapIntensity, 0.05),
      p.normalScale.toArray().map((v) => q(v, 0.05)).join("."), q(p.envMapIntensity, 0.05), p.flatShading,
      texKey(p.map), texKey(p.normalMap), texKey(p.roughnessMap), texKey(p.metalnessMap), texKey(p.aoMap), texKey(p.emissiveMap),
      texKey(p.alphaMap), texKey(p.bumpMap), texKey(p.lightMap),
    )
    if (p.isMeshPhysicalMaterial)
      parts.push(q(p.clearcoat ?? 0, 0.02), q(p.clearcoatRoughness ?? 0, 0.02), q(p.transmission ?? 0, 0.02), q(p.ior ?? 1.5, 0.02),
        q(p.specularIntensity ?? 1, 0.02), c(p.specularColor), q(p.sheen ?? 0, 0.02), q(p.thickness ?? 0, 0.02), q(p.iridescence ?? 0, 0.02),
        texKey(p.clearcoatMap), texKey(p.clearcoatNormalMap), texKey(p.transmissionMap), texKey(p.specularIntensityMap), texKey(p.specularColorMap))
  } else if (p.isMeshBasicMaterial) parts.push(texKey(p.map), texKey(p.alphaMap))
  else parts.push(m.uuid)
  return parts.join("|")
}

