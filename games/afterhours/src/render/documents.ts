export type DocumentId = keyof typeof DOCUMENTS
type Swatch = keyof typeof DOC_SWATCHES
type V3 = readonly [number, number, number]

export type DocumentPlacement = {
  id: DocumentId
  position: V3
  /** Out of the surface (default +Z). */
  normal?: V3
  /** Sheet top direction (default +Y, or −Z when the sheet lies flat). */
  up?: V3
  /** Radians about the normal. */
  rotation?: number
  /** Override the real size (metres). */
  size?: readonly [number, number]
  scale?: number
  /** 0..1, how much the free edges lift off the surface (default 0.25 pinned, 0.1 taped, 0.15 flat). */
  curl?: number
  pin?: "pin" | "tack" | "tape" | "staple" | "none"
  pinColor?: "red" | "blue" | "yellow" | "green" | "white"
  /** Distance off the surface, metres (default 0.0015; stack sheets by raising it). */
  offset?: number
  /** Variation seed (curl shape, pin offsets). */
  seed?: number
}

const BASE = `${import.meta.env.BASE_URL}models/documents/`
let material: THREE.Material | null = null

/** The one material for every document, pin and tape strip (shares the model library's shader). */
export function documentMaterial(): THREE.Material {
  return (material ??= atlasMaterial({ base: `${BASE}base.ktx2`, normal: `${BASE}normal.ktx2`, orm: `${BASE}orm.ktx2` }, "documents"))
}

export function documentsByTag(tag: DocumentTag): DocumentId[] {
  return (Object.keys(DOCUMENTS) as DocumentId[]).filter((id) => (DOCUMENTS[id].tags as readonly DocumentTag[]).includes(tag))
}

const rng = (seed: number) => () => ((seed = (seed * 16807) % 2147483647) / 2147483647)

/** Sheet basis: right, up, normal (world). */
function basis(p: DocumentPlacement) {
  const n = new THREE.Vector3(...(p.normal ?? [0, 0, 1])).normalize()
  const flat = Math.abs(n.y) > 0.9
  const up = new THREE.Vector3(...(p.up ?? (flat ? [0, 0, -1] : [0, 1, 0])))
  up.addScaledVector(n, -up.dot(n)).normalize()
  if (p.rotation) up.applyAxisAngle(n, p.rotation)
  const right = new THREE.Vector3().crossVectors(up, n).normalize()
  return { right, up, n, flat }
}

function sheet(p: DocumentPlacement, rnd: () => number): THREE.BufferGeometry {
  const info: DocumentInfo = DOCUMENTS[p.id]
  const k = p.scale ?? 1
  const [w, h] = [(p.size ?? info.size)[0] * k, (p.size ?? info.size)[1] * k]
  const { right, up, n, flat } = basis(p)
  const pin = p.pin ?? (flat ? "none" : "pin")
  const curl = (p.curl ?? (flat ? 0.15 : pin === "tape" ? 0.1 : pin === "none" || pin === "staple" ? 0.12 : 0.25)) * Math.min(w, h) * 0.12
  const nx = 6
  const ny = Math.max(6, Math.round((6 * h) / w))
  const [u0, v0, u1, v1] = info.uv
  const pos: number[] = []
  const uvs: number[] = []
  const idx: number[] = []
  const lift = p.offset ?? 0.0015
  const c = new THREE.Vector3(...p.position).addScaledVector(n, lift)
  const flatEdge = Math.floor(rnd() * 4)
  const tmp = new THREE.Vector3()
  for (let j = 0; j <= ny; j++)
    for (let i = 0; i <= nx; i++) {
      const s = i / nx
      const t = j / ny // 0 top, 1 bottom
      let d: number
      if (flat) {
        // Flat sheets: one random edge lifts.
        const e = [1 - t, t, 1 - s, s][flatEdge]!
        d = curl * Math.max(0, e - 0.6) ** 2 * 6
      } else if (pin === "tape") d = curl * t ** 2 * (0.3 + Math.abs(s - 0.5))
      else d = curl * (t ** 2 * (0.4 + 1.6 * Math.abs(s - 0.5) ** 1.5) + (pin === "pin" || pin === "tack" ? 0.6 * Math.abs(s - 0.5) ** 2 * (1 - t) : 0))
      d += (rnd() - 0.5) * 0.0004
      tmp.copy(c).addScaledVector(right, (s - 0.5) * w).addScaledVector(up, (0.5 - t) * h).addScaledVector(n, d)
      pos.push(tmp.x, tmp.y, tmp.z)
      uvs.push(u0 + (u1 - u0) * s, v0 + (v1 - v0) * t)
    }
  for (let j = 0; j < ny; j++)
    for (let i = 0; i < nx; i++) {
      const a = j * (nx + 1) + i
      idx.push(a, a + nx + 1, a + 1, a + 1, a + nx + 1, a + nx + 2)
    }
  const g = new THREE.BufferGeometry()
  g.setAttribute("position", new THREE.Float32BufferAttribute(pos, 3))
  g.setAttribute("uv", new THREE.Float32BufferAttribute(uvs, 2))
  g.setIndex(idx)
  g.computeVertexNormals()
  const parts = [g]
  // Fasteners.
  const top = new THREE.Vector3().copy(c).addScaledVector(up, h / 2)
  const swatchGeo = (geo: THREE.BufferGeometry, sw: Swatch) => {
    const [u, v] = DOC_SWATCHES[sw] as readonly [number, number]
    const uv = new Float32Array(geo.getAttribute("position").count * 2)
    for (let i = 0; i < uv.length; i += 2) (uv[i] = u), (uv[i + 1] = v)
    geo.setAttribute("uv", new THREE.BufferAttribute(uv, 2))
    return geo.index ? geo : geo
  }
  const place = (geo: THREE.BufferGeometry, at: THREE.Vector3, yaw = 0) => {
    const m = new THREE.Matrix4().makeBasis(right, n, up.clone().negate())
    m.multiply(new THREE.Matrix4().makeRotationY(yaw))
    m.setPosition(at)
    geo.applyMatrix4(m)
    return geo
  }
  const clean = (geo: THREE.BufferGeometry) => {
    const out = geo.toNonIndexed()
    for (const k2 of Object.keys(out.attributes)) if (!["position", "normal", "uv"].includes(k2)) out.deleteAttribute(k2)
    const ix = [...Array(out.getAttribute("position").count).keys()]
    out.setIndex(ix)
    return out
  }
  if (pin === "pin") {
    const at = top.clone().addScaledVector(up, -0.012).addScaledVector(right, (rnd() - 0.5) * 0.01)
    const head = new THREE.CylinderGeometry(0.0045, 0.0055, 0.006, 10)
    head.translate(0, 0.006, 0)
    const cap = new THREE.CylinderGeometry(0.0065, 0.0065, 0.002, 12)
    cap.translate(0, 0.0095, 0)
    const sw = `pin_${p.pinColor ?? (["red", "blue", "yellow", "green", "white"] as const)[Math.floor(rnd() * 5)]}` as Swatch
    parts.push(swatchGeo(clean(place(head, at)), sw), swatchGeo(clean(place(cap, at)), sw))
    const shaft = new THREE.CylinderGeometry(0.0006, 0.0006, 0.004, 5)
    shaft.translate(0, 0.002, 0)
    parts.push(swatchGeo(clean(place(shaft, at)), "steel"))
  } else if (pin === "tack") {
    const at = top.clone().addScaledVector(up, -0.01)
    const disc = new THREE.CylinderGeometry(0.0055, 0.0055, 0.0012, 12)
    disc.translate(0, 0.0012, 0)
    parts.push(swatchGeo(clean(place(disc, at)), rnd() < 0.5 ? "brass" : "steel"))
  } else if (pin === "tape") {
    for (const sx of [-1, 1]) {
      const at = top.clone().addScaledVector(right, sx * (w / 2 - 0.008)).addScaledVector(n, 0.0004)
      const strip = new THREE.BoxGeometry(0.05, 0.0003, 0.019)
      parts.push(swatchGeo(clean(place(strip, at, sx * (Math.PI / 4) + (rnd() - 0.5) * 0.3)), "tape"))
    }
  } else if (pin === "staple") {
    for (const sx of [-1, 1]) {
      const at = top.clone().addScaledVector(up, -0.01).addScaledVector(right, sx * w * 0.3)
      const st = new THREE.BoxGeometry(0.012, 0.0008, 0.0009)
      parts.push(swatchGeo(clean(place(st, at, (rnd() - 0.5) * 0.4)), "steel"))
    }
  }
  return parts.length > 1 ? mergeGeometries(parts.map((q) => (q.index ? q : clean(q))), false)! : g
}

/** World-space geometry for a set of documents (with their pins/tape), for `documentMaterial()`. */
export function documentGeometry(placements: readonly DocumentPlacement[]): THREE.BufferGeometry {
  const geos = placements.map((p, i) => sheet(p, rng(1 + (p.seed ?? i * 7919 + 13))))
  const g = mergeGeometries(geos, false)
  for (const q of geos) q.dispose()
  if (!g) throw new Error("documentGeometry: nothing to merge")
  g.computeBoundingSphere()
  return g
}

/** One mesh (one draw) for a set of documents. Paper doesn't cast shadows (it lies on a surface); it receives them. */
export function documentMesh(placements: readonly DocumentPlacement[]): THREE.Mesh {
  const mesh = new THREE.Mesh(documentGeometry(placements), documentMaterial())
  mesh.name = `documents×${placements.length}`
  mesh.receiveShadow = true
  mesh.castShadow = false
  mesh.matrixAutoUpdate = false
  return mesh
}
