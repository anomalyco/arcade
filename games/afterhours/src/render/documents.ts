// Set-dressing paperwork for the 1984 station: memos, notices, rosters, forms, posters, a green-bar printout,
// polaroids, sticky notes — legible up close, all invented content following docs/building-program.md (Pine Hollow
// Station, the Sublevel / SL, freight lift FL-1, riser W-1, room numbers and vignettes). Built by scripts/build-documents.ts into one KTX2 atlas (public/models/documents/); the
// whole set is ONE material that shares the model library's shader, so every piece of paper in the building plus its
// pins and tape can be one merged draw.
//
// Placing paper:
//   const docs = documentMesh([
//     { id: "notice_sublevel", position: [x, y, z], normal: [0, 0, 1], rotation: 0.03, pin: "pin", curl: 0.4 },
//     { id: "memo_signin", position: [x, deskY, z], normal: [0, 1, 0], up: [0, 0, -1], rotation: 0.4 },  // flat on a desk
//   ])
//   root.add(docs)
// or `documentGeometry(placements)` to merge into your own batch with `documentMaterial()`.
//
// - `position` is the centre of the sheet ON the surface; it is lifted 1.5 mm (`offset`) along `normal`.
// - `normal` points out of the surface (towards the viewer); `up` is the sheet's top direction (default world +Y for
//   walls, and for flat sheets −Z unless given). `rotation` (radians) turns the sheet about the normal.
// - `size` defaults to the document's real size (Letter 0.216×0.279 m, etc.); `scale` multiplies it.
// - `curl` 0..1 lifts the free edges off the surface (pinned sheets curl at the bottom corners, taped ones less; flat
//   desk sheets lift at a random edge). `pin`: "pin" (round push pin, colour by `pinColor`), "tack" (flat steel thumb
//   tack), "tape" (two strips of masking tape on the top corners), "staple" (two staples), "none".
// - Pick by tag with `documentsByTag("board" | "wall" | "desk" | "clipboard" | "creepy" | "floor")`.

